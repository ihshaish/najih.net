"""Extract official Tawjihi papers from cached Ministry RAR archives, classify them by
subject / session / paper, copy them into exams/ with clean ASCII names, and write
assets/js/exams.js (the index the site reads).

Usage:  python3 -I tools/build_exams.py CACHE_DIR scientific,literary
(CACHE_DIR holds <branch>_<year>.rar files downloaded by tools/fetch_exams.py)

Classification rules are deliberately explicit; anything unrecognised is reported and skipped.
Session numbers come from the FOLDER name (filenames are sometimes wrong)."""
import json, os, re, shutil, subprocess, sys, tempfile, unicodedata

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
cache, branches = sys.argv[1], sys.argv[2].split(",")
cfg = json.load(open(os.path.join(ROOT, "tools", "exam_sources.json"), encoding="utf-8"))
NFC = lambda s: unicodedata.normalize("NFC", s)

SUBJECTS = [  # order matters: first match wins
    ("christian", ["مسيح"]),
    ("islamic", ["اسلامي", "إسلامي", "أسلامي"]),
    ("sci_culture", ["ثقافة علمية", "الثقافة العلمية"]),
    ("math", ["رياضيات"]),
    ("physics", ["فيزياء"]),
    ("chemistry", ["كيمياء"]),
    ("biology", ["أحياء", "احياء", "العلوم الحياتية"]),
    ("english", ["انجليز", "إنجليز"]),
    ("arabic", ["عربية"]),
    ("tech", ["تكنولوجيا", "تكنوجيا"]),
    ("history", ["تاريخ"]),
    ("geography", ["جغرافيا"]),
]
def subject_of(name):
    for sid, kws in SUBJECTS:
        if any(k in name for k in kws): return sid
    return None

def session_of(folder):
    if re.search(r"الأولى|الاولى", folder): return 1
    if re.search(r"الثانية", folder): return 2
    if re.search(r"الثالثة|الاستكمالية", folder): return 3
    return None

def paper_of(name, sub):
    n = name
    if re.search(r"(الورقة|ورقة)\s*(الأولى|الاولى|اولى|ألاولى)|ورقة\s*1|الورقة\s*1|مطالعة", n): return 1
    if re.search(r"(الورقة|ورقة)\s*(الثانية|ثانية)|ورقة\s*2|الورقة\s*2|جلسة ثانية أدب", n): return 2
    if sub == "english":
        m = re.search(r"(?:الإنجليزية|الانجليزية)\s*([12])\b", n)
        if m: return int(m.group(1))
    return None

def variant_of(name):
    if "ضفة" in name or "الضفة" in name: return "wb"
    if "البديل" in name: return "alt"
    if "غزة" in name: return "gz"
    return None

def pages_of(path):
    try:
        import fitz
        return fitz.open(path).page_count
    except Exception:
        return None

papers, skipped = [], []
out_root = os.path.join(ROOT, "exams")
for b in branches:
    for y in ("2022", "2023", "2024", "2025"):
        rar = os.path.join(cache, f"{b}_{y}.rar")
        if not os.path.exists(rar): print("missing", rar); continue
        tmp = tempfile.mkdtemp(prefix="najih_")
        subprocess.run(["bsdtar", "-xf", rar, "-C", tmp], check=True)
        for r, _, fs in os.walk(tmp):
            for f in fs:
                if not f.lower().endswith(".pdf"): continue
                full = os.path.join(r, f)
                name, folder = NFC(f), NFC(os.path.basename(r))
                sub, ses = subject_of(name), session_of(folder)
                if not sub or not ses:
                    skipped.append(f"{b} {y} | {folder} | {name}"); continue
                p, v = paper_of(name, sub), variant_of(name)
                pid = f"{y}-{b}-{sub}-s{ses}" + (f"-p{p}" if p else "") + (f"-{v}" if v else "")
                base = pid; k = 2
                while any(x["id"] == pid for x in papers): pid = f"{base}-{k}"; k += 1
                rel = f"exams/{y}/{b}/{pid.split('-', 2)[2]}.pdf"
                os.makedirs(os.path.join(ROOT, os.path.dirname(rel)), exist_ok=True)
                shutil.copyfile(full, os.path.join(ROOT, rel))
                papers.append({"id": pid, "b": b, "y": int(y), "s": ses, "sub": sub, "p": p, "v": v,
                               "file": rel, "kb": round(os.path.getsize(full) / 1024), "pages": pages_of(full), "orig": name})
        shutil.rmtree(tmp)

papers.sort(key=lambda x: (-x["y"], x["b"], x["sub"], x["s"], x["p"] or 0, x["v"] or ""))
rars = {k: v["files"] for k, v in cfg["branches"].items()}
names = {k: v["name"] for k, v in cfg["branches"].items()}
js = ("// GENERATED by tools/build_exams.py — do not edit by hand.\n"
      "// Official Tawjihi papers published by the Palestinian Ministry of Education and Higher Education\n"
      "// (البوابة التعليمية الفلسطينية). Copies are hosted with credit; the source is " + cfg["source"] + "\n"
      "window.EXAMS = " + json.dumps({"source": cfg["source"], "branchNames": names, "rars": rars, "papers": papers}, ensure_ascii=False, indent=0) + ";\n")
open(os.path.join(ROOT, "assets", "js", "exams.js"), "w", encoding="utf-8").write(js)
print(f"{len(papers)} papers written; {len(skipped)} skipped")
for s in skipped: print("  SKIPPED", s)
from collections import Counter
print(Counter((x["b"], x["y"]) for x in papers))
print("no paper number for:", [x["id"] for x in papers if x["sub"] in ("math", "arabic", "english") and not x["p"]][:40])
