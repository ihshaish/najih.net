"""Build assets/js/curriculum.js from tools/curriculum_source.json (official Grade-12 textbooks, elearn.edu.ps).
Usage: python3 -I tools/build_curriculum.py"""
import json, os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
src = json.load(open(os.path.join(ROOT, "tools", "curriculum_source.json"), encoding="utf-8"))
BRANCH = {"c12s": "scientific", "c12h": "literary", "c12re": "sharia", "c12ri": "entre", "c12in": "industrial", "c12agr": "agricultural"}
SUBJ = [("Reading Plus", "english"), ("الإنجليزية", "english"), ("الرياضيات", "math"), ("العربية", "arabic"), ("الفيزياء", "physics"),
        ("الكيمياء", "chemistry"), ("الحياتية", "biology"), ("الإسلامية", "islamic"), ("التكنولوجيا", "tech"), ("المسيحية", "christian"),
        ("الجغرافية", "geography"), ("التاريخية", "history"), ("الثقافة العلمية", "sci_culture"), ("القرآن", "quran"), ("الحديث", "hadith"),
        ("الفقه", "fiqh"), ("الدعوة", "dawah"), ("إدارة", "mgmt"), ("المحاسبة", "accounting"), ("المشاريع", "projects"), ("الرسم", "drawing")]
OFFSET = {"ma12-s.pdf": 4, "ma12-in.pdf": 4}  # printed page → PDF page offset (verified for scientific maths)
LINKS = {  # Najih interactive lessons attached to official lessons (matched by lesson-number / title prefix)
    ("math", "1-1"): ["derivative-intro"], ("math", "1-2"): ["derivative-intro"],
    ("physics", "الفصل الرابع"): ["ohms-law"], ("chemistry", "3-3"): ["ph-basics"],
}
def split_title(t):
    t = re.sub(r"\s*[–-]\s*(ص|p\.)\s*\d+\s*$", "", t).strip()
    m = re.match(r"^(.*?)\s*\(([A-Za-z][^()]*(?:\([^()]*\))?[^()]*)\)\s*(.*)$", t)
    if m and re.search(r"[؀-ۿ]", m.group(1)):
        return {"ar": (m.group(1) + (" " + m.group(3) if m.group(3) else "")).strip(), "en": m.group(2).strip()}
    if not re.search(r"[؀-ۿ]", t): return {"ar": t, "en": t}
    return {"ar": t, "en": None}
branches = []
for b in src["branches"]:
    if b["slug"] not in BRANCH: continue
    subs = {}
    for k in b["books"]:
        sid = next((v for kw, v in SUBJ if kw in k["subject_ar"] or kw in (k.get("subject_en") or "")), None)
        if not sid: print("UNMAPPED", k["subject_ar"]); continue
        fname = k["url"].rsplit("/", 1)[-1]
        book = {"title": {"ar": k["subject_ar"], "en": k.get("subject_en")}, "part": k.get("part"), "url": k["url"], "mb": round(k["bytes"] / 1e6, 1)}
        if fname in OFFSET: book["off"] = OFFSET[fname]
        units = []
        for u in k["units"]:
            lessons = []
            for l in u["lessons"]:
                t = split_title(l["title"]); key = re.match(r"^(\d+[-.]\d+|الفصل [^:\s]+)", t["ar"])
                item = {"t": t, "pg": l.get("page")}
                nj = LINKS.get((sid, key.group(1) if key else ""))
                if nj: item["najih"] = nj
                lessons.append(item)
            units.append({"t": split_title(u["title"]), "lessons": lessons})
        book["units"] = units
        subs.setdefault(sid, []).append(book)
    branches.append({"id": BRANCH[b["slug"]], "slug": b["slug"], "page": b["page"], "subjects": [{"sub": s, "books": v} for s, v in subs.items()]})
js = ("// GENERATED by tools/build_curriculum.py from the official Grade-12 textbooks on https://elearn.edu.ps — do not edit by hand.\n"
      "window.CURRICULUM = " + json.dumps({"branches": branches}, ensure_ascii=False) + ";\n")
open(os.path.join(ROOT, "assets", "js", "curriculum.js"), "w", encoding="utf-8").write(js)
for b in branches: print(b["id"], [s["sub"] for s in b["subjects"]])
